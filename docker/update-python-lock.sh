#!/usr/bin/env bash
# Regenerates docker/constraints.txt (exact Python package versions of the runtime image)
# for linux/amd64 and linux/arm64. Requires Docker with buildx; the foreign architecture
# is emulated via QEMU, which Docker Desktop provides out of the box.
set -euo pipefail

cd "$(dirname "$0")"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

for arch in amd64 arm64; do
  echo ">>> Resolving Python dependencies for linux/$arch"
  docker buildx build \
    --platform "linux/$arch" \
    --target python-lock-export \
    --output "type=local,dest=$tmp/$arch" \
    .
done

python3 - "$tmp/amd64/constraints.txt" "$tmp/arm64/constraints.txt" > constraints.txt <<'EOF'
import sys

def read(path):
    pins = {}
    for line in open(path):
        line = line.strip()
        if line and not line.startswith("#"):
            name, version = line.split("==", 1)
            pins[name.lower()] = (name, version)
    return pins

amd64, arm64 = read(sys.argv[1]), read(sys.argv[2])
print("# Generated by update-python-lock.sh - do not edit by hand.")
for key in sorted(amd64.keys() | arm64.keys()):
    a, b = amd64.get(key), arm64.get(key)
    if a == b:
        print(f"{a[0]}=={a[1]}")
        continue
    if a:
        print(f'{a[0]}=={a[1]} ; platform_machine == "x86_64"')
    if b:
        print(f'{b[0]}=={b[1]} ; platform_machine == "aarch64"')
EOF

echo ">>> Wrote $(pwd)/constraints.txt"
